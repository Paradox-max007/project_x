// ---------------------------------------------------------------------------
// Uniform issues
// ---------------------------------------------------------------------------

export const UNIFORM_ISSUE_INCLUDE = {
  employee: { select: { fullName: true, employeeCode: true } },
  site: { select: { name: true } },
  items: { include: { item: true } },
} satisfies Prisma.UniformIssueInclude;

export type UniformIssueWithRelations = Prisma.UniformIssueGetPayload<{
  include: typeof UNIFORM_ISSUE_INCLUDE;
}>;

/**
 * Serialize a uniform issue. `maskDocument` controls whether the decrypted
 * document number is masked (list views) or returned in full (creator views).
 */
export function toUniformIssueRecord(
  row: UniformIssueWithRelations,
  opts: { maskDocument?: boolean } = {}
): UniformIssueRecord {
  const documentNumber = decryptField(row.documentNumber);
  return {
    id: row.id,
    uniformCode: row.uniformCode,
    tokenNumber: row.tokenNumber,
    employeeId: row.employeeId,
    employeeName: row.employee.fullName,
    employeeCode: row.employee.employeeCode,
    documentType: row.documentType,
    documentNumber: opts.maskDocument
      ? maskValue(documentNumber) ?? ""
      : documentNumber ?? "",
    siteId: row.siteId,
    siteName: row.site?.name ?? null,
    teamLeaderName: row.teamLeaderName,
    isRenewal: row.isRenewal,
    previousIssueId: row.previousIssueId,
    issuedAt: row.issuedAt.toISOString(),
    renewalDate: dateToYmd(row.renewalDate),
    createdByName: row.createdByName,
    items: row.items
      .map((i) => ({ itemId: i.itemId, name: i.item.name, quantity: i.quantity }))
      .sort((a, b) => a.name.localeCompare(b.name)),
  };
}

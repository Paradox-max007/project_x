import "server-only";
import type { Prisma } from "@prisma/client";
import { decryptField, maskValue } from "@/lib/crypto";
import { dateToYmd } from "@/lib/ops-helpers";
import type {
  LeaveRequestRecord,
  WarningRecord,
  FineRecord,
  CancellationRecord,
  UniformIssueRecord,
} from "@/types/manpower";

// ---------------------------------------------------------------------------
// Leave requests
// ---------------------------------------------------------------------------

export const LEAVE_INCLUDE = {
  employee: { select: { fullName: true, employeeCode: true } },
} satisfies Prisma.LeaveRequestInclude;

export type LeaveWithEmployee = Prisma.LeaveRequestGetPayload<{
  include: typeof LEAVE_INCLUDE;
}>;

export function toLeaveRecord(row: LeaveWithEmployee): LeaveRequestRecord {
  return {
    id: row.id,
    employeeId: row.employeeId,
    employeeName: row.employee.fullName,
    employeeCode: row.employee.employeeCode,
    leaveType: row.leaveType as LeaveRequestRecord["leaveType"],
    otherType: row.otherType,
    startDate: dateToYmd(row.startDate),
    endDate: dateToYmd(row.endDate),
    totalDays: row.totalDays,
    reason: row.reason,
    status: row.status as LeaveRequestRecord["status"],
    createdByName: row.createdByName,
    reviewedByName: row.reviewedByName,
    reviewedAt: row.reviewedAt ? row.reviewedAt.toISOString() : null,
    createdAt: row.createdAt.toISOString(),
  };
}

// ---------------------------------------------------------------------------
// Warnings
// ---------------------------------------------------------------------------

export const WARNING_INCLUDE = {
  employee: { select: { fullName: true, employeeCode: true } },
} satisfies Prisma.WarningInclude;

export type WarningWithEmployee = Prisma.WarningGetPayload<{
  include: typeof WARNING_INCLUDE;
}>;

/** Parse the JSON-string absentDates column into a clean string[]. */
export function parseAbsentDates(json: string | null): string[] {
  if (!json) return [];
  try {
    const parsed: unknown = JSON.parse(json);
    if (!Array.isArray(parsed)) return [];
    return parsed.filter((x): x is string => typeof x === "string");
  } catch {
    return [];
  }
}

export function toWarningRecord(row: WarningWithEmployee): WarningRecord {
  return {
    id: row.id,
    employeeId: row.employeeId,
    employeeName: row.employee.fullName,
    employeeCode: row.employee.employeeCode,
    reason: row.reason,
    isAutoGenerated: row.isAutoGenerated,
    absentDates: parseAbsentDates(row.absentDates),
    ratingPenalty: row.ratingPenalty,
    createdByName: row.createdByName,
    createdAt: row.createdAt.toISOString(),
  };
}

